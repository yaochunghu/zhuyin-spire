/**
 * Large shared phrase pools for cast checks.
 * Cards only fix the 注音 initial; each cast draws a fresh phrase so practice stays varied.
 *
 * Rules (same as card cues):
 * - First syllable starts with the given 注音
 * - spell = full first syllable including 聲調 (omit mark for 一聲)
 * - emoji depicts the word
 */

import type { Cue } from './cards';

export type PhrasePack =
  | 'core'
  | 'home'
  | 'park'
  | 'food'
  | 'body'
  | 'school'
  | 'animals'
  | 'nature'
  | 'numbers'
  | 'family';

export interface Phrase extends Cue {
  packs: PhrasePack[];
}

function p(
  word: string,
  emoji: string,
  spell: string,
  packs: PhrasePack[] = ['core'],
): Phrase {
  return { word, emoji, spell, packs };
}

