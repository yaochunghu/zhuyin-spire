/**
 * Rewrite the committed v4 save fixtures and choice logs.
 *
 *   npm run generate:save-fixtures
 *
 * The script plays both characters through the real run, map, event, shop,
 * reward, and save code. Edit the harness policy, not the JSON.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  FIXTURE_SCREENS,
  REPLAY_FIXTURE_DIR,
  SAVE_FIXTURE_DIR,
  assertSnapshotRoundTrip,
  findFixtureSeed,
  fixtureFileName,
  replayFileName,
  runReplay,
  type FixtureScreen,
  type RecordedReplay,
} from '../tests/support/saveReplayHarness';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function writeJson(relativePath: string, value: unknown): void {
  const file = path.join(root, relativePath);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`);
}

function writeCharacter(recorded: RecordedReplay): void {
  for (const screen of FIXTURE_SCREENS) {
    const snapshot = recorded.snapshots[screen];
    if (!snapshot) throw new Error(`${recorded.characterId} has no ${screen} snapshot`);
    assertSnapshotRoundTrip(snapshot);
    writeJson(path.join(SAVE_FIXTURE_DIR, fixtureFileName(recorded.characterId, screen)), snapshot);
  }
  writeJson(path.join(REPLAY_FIXTURE_DIR, replayFileName(recorded.characterId)), {
    note: 'Generated by npm run generate:save-fixtures. Do not edit by hand.',
    seed: recorded.seed,
    characterId: recorded.characterId,
    choices: recorded.choices,
  });
}

describe('generate save fixtures', () => {
  it('writes v4 checkpoints and choice logs for both characters', () => {
    const { echo, abacus } = findFixtureSeed();
    expect(echo.seed).toBe(abacus.seed);
    for (const screen of FIXTURE_SCREENS) {
      expect(echo.snapshots[screen]?.v).toBe(4);
      expect(abacus.snapshots[screen]?.v).toBe(4);
      expect(echo.snapshots[screen]?.screen).toBe(screen satisfies FixtureScreen);
      expect(abacus.snapshots[screen]?.screen).toBe(screen);
    }
    writeCharacter(echo);
    writeCharacter(abacus);
    for (const recorded of [echo, abacus]) {
      const resumed = runReplay(recorded, 'resume');
      expect(JSON.stringify(resumed.finalSnapshot)).toBe(JSON.stringify(recorded.finalSnapshot));
      expect(resumed.prompts).toEqual(recorded.prompts);
    }
  });
});
