// Register already-copied batch 3 extras without writing any audio assets.
// Usage: node scripts/import-voice-extras.mjs <batch3_extras directory>
import { readFile, writeFile, access } from 'node:fs/promises';
import { join } from 'node:path';
const root = process.argv[2];
if (!root) throw new Error('Expected batch3_extras directory');
const handoff = (await readFile(join(root, 'HANDOFF_LIST.txt'), 'utf8')).trim().split(/\r?\n/u);
if (handoff.length !== 462 || new Set(handoff).size !== 462) throw new Error('Expected 462 unique clips');
const rows = new Map();
for (const line of (await readFile(join(root, 'MANIFEST.md'), 'utf8')).split('\n')) {
  const cells = line.split('|').map(cell => cell.trim());
  if (handoff.includes(cells[2])) rows.set(cells[2], [cells[1], cells[4]]);
}
const body = [];
for (const file of handoff) {
  if (!/^(enemy|math|potion|relic)\/[^/]+\.mp3$/u.test(file)) throw new Error(`Unexpected path: ${file}`);
  const row = rows.get(file);
  if (!row || row[0] === 'e.elitePrism.name') throw new Error(`Unexpected manifest row: ${file}`);
  await access(join('src/assets/audio/voice/teacher/extras_b3', file));
  body.push(`  ${JSON.stringify(row[0])}: ['teacher', ${JSON.stringify(`teacher/extras_b3/${file}`)}, ${JSON.stringify(row[1])}],`);
}
await writeFile('src/data/voiceExtras.ts', `/** Generated by scripts/import-voice-extras.mjs from the batch 3 extras handoff and manifest.
 * ElevenLabs eleven_v4, generated for this project. See THIRD_PARTY_NOTICES.md.
 * e.elitePrism.name is intentionally absent and keeps its existing fallback.
 */
import type { VoiceSpeaker } from './voiceLines';

export const VOICE_EXTRAS: Readonly<Record<string, readonly [VoiceSpeaker, string, string]>> = {
${body.join('\n')}
};
`);
